    // ------------------------------------------------------------ passes ---
    void beginPass(FramebufferHandle fb, int x, int y, int w, int h, const ClearDesc& c) override {
        if (!beginFrameIfNeeded()) return;
        std::array<D3D12_CPU_DESCRIPTOR_HANDLE, 4> rtv{};
        D3D12_CPU_DESCRIPTOR_HANDLE dsv{};
        bool hasDsv = false;
        m_rtCount = 0;
        m_rtFormats.fill(DXGI_FORMAT_UNKNOWN);
        m_dsvFormat = DXGI_FORMAT_UNKNOWN;
        m_samples = 1;
        if (fb) {
            auto it = m_fbs.find(fb.id);
            if (it == m_fbs.end()) return;
            const FramebufferDesc& d = it->second.desc;
            for (int i = 0; i < d.colorCount; ++i) {
                Tex12* t = tex(d.colors[static_cast<size_t>(i)].texture);
                if (!t) continue;
                setState(t->res.get(), t->state, D3D12_RESOURCE_STATE_RENDER_TARGET);
                rtv[static_cast<size_t>(m_rtCount)] = m_rtvCpu.cpu(rtvFor(*t, d.colors[static_cast<size_t>(i)]));
                m_rtFormats[static_cast<size_t>(m_rtCount)] = d3d::dxgiFormat(t->desc.format, t->desc.srgb);
                m_samples = std::max(1, t->desc.samples);
                ++m_rtCount;
            }
            if (Tex12* t = tex(d.depth.texture)) {
                setState(t->res.get(), t->state, D3D12_RESOURCE_STATE_DEPTH_WRITE);
                dsv = m_dsvCpu.cpu(dsvFor(*t, d.depth));
                hasDsv = true;
                m_dsvFormat = DXGI_FORMAT_D32_FLOAT;
                m_samples = std::max(1, t->desc.samples);
            }
        } else {
            setState(m_backbuffers[m_frameIndex].get(), m_backState, D3D12_RESOURCE_STATE_RENDER_TARGET);
            rtv[0] = m_rtvCpu.cpu(m_backRtv[m_frameIndex]);
            m_rtFormats[0] = m_backFormat;
            m_rtCount = 1;
            dsv = m_dsvCpu.cpu(m_backDsv);
            hasDsv = true;
            m_dsvFormat = DXGI_FORMAT_D32_FLOAT;
        }
        flushBarriers();
        m_list->OMSetRenderTargets(static_cast<UINT>(m_rtCount), m_rtCount ? rtv.data() : nullptr, FALSE, hasDsv ? &dsv : nullptr);
        if (c.color) {
            float col[4] = {c.colorValue.x, c.colorValue.y, c.colorValue.z, c.colorValue.w};
            for (int i = 0; i < m_rtCount; ++i) m_list->ClearRenderTargetView(rtv[static_cast<size_t>(i)], col, 0, nullptr);
        }
        if (c.depth && hasDsv) m_list->ClearDepthStencilView(dsv, D3D12_CLEAR_FLAG_DEPTH, c.depthValue, 0, 0, nullptr);
        D3D12_VIEWPORT vp{static_cast<float>(x), static_cast<float>(y), static_cast<float>(w), static_cast<float>(h), 0.0f, 1.0f};
        D3D12_RECT sc{x, y, x + w, y + h};
        m_list->RSSetViewports(1, &vp);
        m_list->RSSetScissorRects(1, &sc);
        bindRoot();
        m_depthTest = m_depthWrite = true;
        m_depthFunc = DepthFunc::Less;
        m_blend = BlendMode::None;
        m_passOpen = true;
        ++m_stats.passes;
    }
    void beginPass(RenderTargetHandle rt, int w, int h, Vec4 clearColor) override {
        ClearDesc cd;
        cd.colorValue = clearColor;
        beginPass(rt ? framebufferOf(rt) : FramebufferHandle{}, 0, 0, w, h, cd);
    }
    void endPass() override {}

