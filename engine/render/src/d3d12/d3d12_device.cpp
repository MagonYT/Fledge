    // ----------------------------------------------------------- present ---
    void present() override {
        if (!beginFrameIfNeeded()) return;  // nothing rendered: still present a cleared frame
        setState(m_backbuffers[m_frameIndex].get(), m_backState, D3D12_RESOURCE_STATE_PRESENT);
        flushBarriers();
        submit();
        UINT flags = (!m_vsync && m_wantTearing && m_tearingSupported) ? DXGI_PRESENT_ALLOW_TEARING : 0;
        m_swapchain->Present(m_vsync ? 1 : 0, flags);
        m_frameFence[m_frameIndex] = ++m_fenceValue;
        m_queue->Signal(m_fence.get(), m_fenceValue);
        m_frameIndex = m_swapchain->GetCurrentBackBufferIndex();
        waitFor(m_frameFence[m_frameIndex]);
        collectGarbage(m_frameIndex);
        m_frameOpen = false;
        ++m_frameNumber;
        dumpDebugMessages();
    }
    void resizeSwapchain(int w, int h) override {
        if (w <= 0 || h <= 0 || (w == m_width && h == m_height) || m_frameOpen) return;
        waitIdle();
        for (auto& g : m_garbage) g.clear();
        for (auto& bb : m_backbuffers) bb.reset();
        m_backDepth.reset();
        if (FAILED(m_swapchain->ResizeBuffers(kFrames, static_cast<UINT>(w), static_cast<UINT>(h), m_backFormat,
                                              m_tearingSupported ? DXGI_SWAP_CHAIN_FLAG_ALLOW_TEARING : 0))) {
            FLEDGE_LOG_ERROR("rhi", "D3D12: ResizeBuffers failed");
            return;
        }
        m_width = w;
        m_height = h;
        m_frameIndex = m_swapchain->GetCurrentBackBufferIndex();
        createBackbufferViews();
    }

