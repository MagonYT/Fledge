// Direct3D 12 RHI backend - full pipeline (see docs/GRAPHICS.md "Direct3D 12").
//
// Feature parity with the GL backend: meshes (+ tangent stream), line meshes, every texture
// format/type (float, depth, cube, arrays, MSAA), framebuffers / render-to-texture with resolve,
// uniform buffers, fullscreen passes, wireframe, blending, GPU mip generation, readback,
// HDR10 swapchain, vsync / tearing (VRR). Ray tracing (DXR) lives in d3d12_raytracing.cpp.
//
// Design:
//   * root signature: b0 = Frame CBV, b1 = per-draw Params CBV (both root descriptors pointing
//     into a per-frame upload ring), t0-t15 SRV table, s0-s15 sampler table
//   * persistent CPU descriptor heaps (SRV / RTV / DSV) with free lists; per draw the bound SRVs
//     are copied into a per-frame range of a shader-visible ring; sampler tables are deduplicated
//   * PSOs are created lazily per (shader, raster/depth/blend state, target formats, samples)
//   * whole-resource state tracking (per-subresource only inside generateMips)
//   * destroyed resources are released once the GPU is done with the frame that used them
// The newer d3d12.h comes from microsoft/DirectX-Headers (pinned); d3d12.dll, dxgi.dll and
// d3dcompiler_47.dll are loaded at runtime.
#ifdef _WIN32
// DirectX-Headers are generated by MIDL 8.01 and ask for rpcndr 500; MinGW ships 475, which has
// everything d3d12.h uses.
#define __REQUIRED_RPCNDR_H_VERSION__ 475
#include <directx/d3d12.h>
#include <dxguids/dxguids.h>

#include "../d3d/d3d_common.h"
#include "d3d12_internal.h"
#endif

