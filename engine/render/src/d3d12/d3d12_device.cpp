    void draw(MeshHandle h, Topology t) override {
        auto it = m_meshes.find(h.id);
        if (it == m_meshes.end()) return;
        Mesh12& m = it->second;
        if (m.count == 0) return;
        if (m.lines) {
            if (!prepareDraw(InputKind::Line, true)) return;
            UINT64 bytes = m.lineData.size() * sizeof(LineVertex);
            D3D12_GPU_VIRTUAL_ADDRESS va = ringCopy(m.lineData.data(), bytes, 16);
            if (!va) return;
            D3D12_VERTEX_BUFFER_VIEW v{va, static_cast<UINT>(bytes), sizeof(LineVertex)};
            m_list->IASetVertexBuffers(0, 1, &v);
            m_list->IASetPrimitiveTopology(D3D_PRIMITIVE_TOPOLOGY_LINELIST);
            m_list->DrawInstanced(m.count, 1, 0, 0);
            m_stats.lines += m.count / 2;
        } else {
            bool lines = t == Topology::Lines;
            if (!prepareDraw(InputKind::Mesh, lines)) return;
            m_list->IASetVertexBuffers(0, 2, m.views);
            m_list->IASetIndexBuffer(&m.ibv);
            m_list->IASetPrimitiveTopology(lines ? D3D_PRIMITIVE_TOPOLOGY_LINELIST : D3D_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
            m_list->DrawIndexedInstanced(m.count, 1, 0, 0, 0);
            m_stats.triangles += m.count / 3;
        }
        ++m_stats.drawCalls;
    }
    void drawInstanced(MeshHandle h, int instances) override {
        auto it = m_meshes.find(h.id);
        if (it == m_meshes.end() || it->second.lines || !prepareDraw(InputKind::Mesh, false)) return;
        m_list->IASetVertexBuffers(0, 2, it->second.views);
        m_list->IASetIndexBuffer(&it->second.ibv);
        m_list->IASetPrimitiveTopology(D3D_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
        m_list->DrawIndexedInstanced(it->second.count, static_cast<UINT>(instances), 0, 0, 0);
        ++m_stats.drawCalls;
        m_stats.triangles += it->second.count / 3 * static_cast<uint32_t>(instances);
    }
    void drawFullscreenTriangle() override {
        if (!prepareDraw(InputKind::None, false)) return;
        m_list->IASetPrimitiveTopology(D3D_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
        m_list->DrawInstanced(3, 1, 0, 0);
        ++m_stats.drawCalls;
    }

