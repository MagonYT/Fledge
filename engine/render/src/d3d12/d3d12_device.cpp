    void dumpDebugMessages() {  // debug layer output -> log (FLEDGE_D3D12_DEBUG=1)
        if (!m_infoQueue) return;
        UINT64 n = m_infoQueue->GetNumStoredMessages();
        for (UINT64 i = 0; i < n && m_debugMessages < 200; ++i) {
            SIZE_T len = 0;
            m_infoQueue->GetMessage(i, nullptr, &len);
            std::vector<uint8_t> buf(len);
            auto* msg = reinterpret_cast<D3D12_MESSAGE*>(buf.data());
            if (FAILED(m_infoQueue->GetMessage(i, msg, &len))) continue;
            if (msg->Severity <= D3D12_MESSAGE_SEVERITY_WARNING) {
                FLEDGE_LOG_WARN("rhi", "D3D12 debug: {}", std::string(msg->pDescription, msg->DescriptionByteLength ? msg->DescriptionByteLength - 1 : 0));
                ++m_debugMessages;
            }
        }
        m_infoQueue->ClearStoredMessages();
    }
