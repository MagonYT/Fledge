    void resolve(FramebufferHandle src, FramebufferHandle dst, int, int) override {
        if (!beginFrameIfNeeded()) return;
        auto s = m_fbs.find(src.id);
        if (s == m_fbs.end() || s->second.desc.colorCount == 0) return;
        Tex12* st = tex(s->second.desc.colors[0].texture);
        if (!st) return;
        ID3D12Resource* dstRes = nullptr;
        D3D12_RESOURCE_STATES* dstState = nullptr;
        UINT dstSub = 0;
        DXGI_FORMAT fmt;
        if (dst) {
            auto d = m_fbs.find(dst.id);
            if (d == m_fbs.end() || d->second.desc.colorCount == 0) return;
            Tex12* dt = tex(d->second.desc.colors[0].texture);
            if (!dt) return;
            dstRes = dt->res.get();
            dstState = &dt->state;
            dstSub = static_cast<UINT>(d->second.desc.colors[0].mip) +
                     static_cast<UINT>(d->second.desc.colors[0].layer) * static_cast<UINT>(std::max(1, dt->desc.mips));
            fmt = d3d::dxgiFormat(dt->desc.format, dt->desc.srgb);
        } else {
            dstRes = m_backbuffers[m_frameIndex].get();
            dstState = &m_backState;
            fmt = m_backFormat;
        }
        bool msaa = st->desc.samples > 1;
        setState(st->res.get(), st->state, msaa ? D3D12_RESOURCE_STATE_RESOLVE_SOURCE : D3D12_RESOURCE_STATE_COPY_SOURCE);
        setState(dstRes, *dstState, msaa ? D3D12_RESOURCE_STATE_RESOLVE_DEST : D3D12_RESOURCE_STATE_COPY_DEST);
        flushBarriers();
        if (msaa) {
            m_list->ResolveSubresource(dstRes, dstSub, st->res.get(), 0, fmt);
        } else {
            D3D12_TEXTURE_COPY_LOCATION d{}, sl{};
            d.pResource = dstRes;
            d.Type = D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX;
            d.SubresourceIndex = dstSub;
            sl.pResource = st->res.get();
            sl.Type = D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX;
            m_list->CopyTextureRegion(&d, 0, 0, 0, &sl, nullptr);
        }
        m_passOpen = false;
    }

