void Sha256::block(const uint8_t* p) {
    uint32_t w[64];
    for (int i = 0; i < 16; ++i)
        w[i] = (uint32_t(p[i * 4]) << 24) | (uint32_t(p[i * 4 + 1]) << 16) | (uint32_t(p[i * 4 + 2]) << 8) | uint32_t(p[i * 4 + 3]);
    for (int i = 16; i < 64; ++i) {
        uint32_t s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = m_h[0], b = m_h[1], c = m_h[2], d = m_h[3], e = m_h[4], f = m_h[5], g = m_h[6], h = m_h[7];
    for (int i = 0; i < 64; ++i) {
        uint32_t S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
        uint32_t ch = (e & f) ^ (~e & g);
        uint32_t t1 = h + S1 + ch + K[i] + w[i];
        uint32_t S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
        uint32_t mj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + mj;
        h = g;
        g = f;
        f = e;
        e = d + t1;
        d = c;
        c = b;
        b = a;
        a = t1 + t2;
    }
    m_h[0] += a;
    m_h[1] += b;
    m_h[2] += c;
    m_h[3] += d;
    m_h[4] += e;
    m_h[5] += f;
    m_h[6] += g;
    m_h[7] += h;
}

void Sha256::update(const void* data, size_t size) {
    auto* p = static_cast<const uint8_t*>(data);
    m_total += size;
    while (size > 0) {
        size_t n = std::min(size, sizeof(m_buf) - m_len);
        std::memcpy(m_buf + m_len, p, n);
        m_len += n;
        p += n;
        size -= n;
        if (m_len == 64) {
            block(m_buf);
            m_len = 0;
        }
    }
}

std::array<uint8_t, 32> Sha256::finish() {
    uint64_t bits = m_total * 8;
    uint8_t pad = 0x80;
    update(&pad, 1);
    uint8_t zero = 0;
    while (m_len != 56) update(&zero, 1);
    uint8_t len[8];
    for (int i = 0; i < 8; ++i) len[i] = static_cast<uint8_t>(bits >> (56 - 8 * i));
    update(len, 8);
    std::array<uint8_t, 32> out{};
    for (int i = 0; i < 8; ++i)
        for (int k = 0; k < 4; ++k) out[static_cast<size_t>(i * 4 + k)] = static_cast<uint8_t>(m_h[i] >> (24 - 8 * k));
    return out;
}

std::string Sha256::finishHex() {
    auto d = finish();
    static const char* digits = "0123456789abcdef";
    std::string s;
    s.reserve(64);
    for (uint8_t b : d) {
        s += digits[b >> 4];
        s += digits[b & 15];
    }
    return s;
}

std::string Sha256::hex(const void* data, size_t size) {
    Sha256 h;
    h.update(data, size);
    return h.finishHex();
}

std::string Sha256::fileHex(const fs::path& file) {
    std::ifstream f(osPath(file), std::ios::binary);
    if (!f) return {};
    Sha256 h;
    std::vector<char> buf(1 << 20);
    while (f) {
        f.read(buf.data(), static_cast<std::streamsize>(buf.size()));
        std::streamsize n = f.gcount();
        if (n > 0) h.update(buf.data(), static_cast<size_t>(n));
    }
    return h.finishHex();
}

