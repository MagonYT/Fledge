std::string_view trim(std::string_view s) {
    while (!s.empty() && (s.front() == ' ' || s.front() == '\t' || s.front() == '\r' || s.front() == '\n' || s.front() == '\0')) s.remove_prefix(1);
    while (!s.empty() && (s.back() == ' ' || s.back() == '\t' || s.back() == '\r' || s.back() == '\n' || s.back() == '\0')) s.remove_suffix(1);
    return s;
}
bool startsWithCI(std::string_view s, std::string_view p) {
    if (s.size() < p.size()) return false;
    for (size_t i = 0; i < p.size(); ++i)
        if (std::tolower(static_cast<unsigned char>(s[i])) != std::tolower(static_cast<unsigned char>(p[i]))) return false;
    return true;
}
bool identChar(char c) { return std::isalnum(static_cast<unsigned char>(c)) || c == '_'; }

// Scans a value starting at `i` until a top-level ',' or an unbalanced ')'. Handles "..." (with \ escapes), Word'...' object
// references and nested parentheses (bounded by maxDepth). Returns the end index.
size_t scanValue(std::string_view s, size_t i, int maxDepth) {
    int depth = 0;
    bool inDq = false, inSq = false;
    for (; i < s.size(); ++i) {
        char c = s[i];
        if (inDq) {
            if (c == '\\' && i + 1 < s.size()) ++i;
            else if (c == '"') inDq = false;
            continue;
        }
        if (inSq) {
            if (c == '\'') inSq = false;
            continue;
        }
        if (c == '"') inDq = true;
        else if (c == '\'' && i > 0 && (identChar(s[i - 1]) || s[i - 1] == '>')) inSq = true;
        else if (c == '(') {
            if (++depth > maxDepth) return s.size();
        } else if (c == ')') {
            if (depth == 0) return i;
            --depth;
        } else if (c == ',' && depth == 0) return i;
    }
    return i;
}

// "Key=Value" -> (Key, Value); a line can carry nested parentheses in the value.
std::pair<std::string, std::string> splitKeyValue(std::string_view item) {
    item = trim(item);
    size_t eq = std::string_view::npos;
    int depth = 0;
    bool dq = false;
    for (size_t i = 0; i < item.size(); ++i) {
        char c = item[i];
        if (dq) {
            if (c == '\\' && i + 1 < item.size()) ++i;
            else if (c == '"') dq = false;
            continue;
        }
        if (c == '"') dq = true;
        else if (c == '(') ++depth;
        else if (c == ')') --depth;
        else if (c == '=' && depth <= 0) {
            eq = i;
            break;
        }
        // a key can contain "(n)" (array index) but not quotes or spaces before the '='
    }
    if (eq == std::string_view::npos) return {"", std::string(item)};
    return {std::string(trim(item.substr(0, eq))), std::string(trim(item.substr(eq + 1)))};
}

std::string stripIndex(std::string_view key) {  // "PinNames(0)" -> "PinNames"
    size_t p = key.find('(');
    return std::string(p == std::string_view::npos ? key : key.substr(0, p));
}

// Short name of an object path: Class'"/Script/Engine.Actor"' -> Actor, /Game/BP_X.BP_X_C -> BP_X_C, MacroGraph ...:ForLoop -> ForLoop
std::string shortObjectName(std::string_view v) {
    v = trim(v);
    if (v.empty() || v == "None") return "";
    size_t q1 = v.find('"');
    if (q1 != std::string_view::npos) {
        size_t q2 = v.find('"', q1 + 1);
        v = v.substr(q1 + 1, q2 == std::string_view::npos ? std::string_view::npos : q2 - q1 - 1);
    } else if (size_t a = v.find('\''); a != std::string_view::npos) {
        size_t b = v.find('\'', a + 1);
        v = v.substr(a + 1, b == std::string_view::npos ? std::string_view::npos : b - a - 1);
    }
    size_t cut = v.find_last_of(".:/");
    if (cut != std::string_view::npos) v = v.substr(cut + 1);
    return std::string(trim(v));
}

