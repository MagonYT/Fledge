const Pin* Node::pin(std::string_view n, std::optional<PinDir> dir) const {
    for (auto& p : pins)
        if (p.name == n && (!dir || p.dir == *dir)) return &p;
    return nullptr;
}
const Pin* Node::pinById(std::string_view id) const {
    for (auto& p : pins)
        if (p.id == id) return &p;
    return nullptr;
}
bool Node::hasExecInput() const {
    for (auto& p : pins)
        if (p.dir == PinDir::In && p.type.category == "exec") return true;
    return false;
}
const Node* Graph::find(std::string_view n) const {
    for (auto& x : nodes)
        if (x.name == n) return &x;
    return nullptr;
}

namespace {
std::string valueOf(const std::vector<std::pair<std::string, std::string>>& kv, std::string_view key) {
    for (auto& [k, v] : kv)
        if (k == key) return v;
    return {};
}
bool truthy(std::string_view v) {
    std::string s = toLower(trim(v));
    return s == "true" || s == "1";
}

PinType pinTypeFrom(const std::vector<std::pair<std::string, std::string>>& kv, std::string_view prefix) {
    PinType t;
    auto get = [&](const char* k) { return valueOf(kv, std::string(prefix) + k); };
    t.category = toLower(unquote(get("PinCategory")));
    t.subCategory = toLower(unquote(get("PinSubCategory")));
    t.subObject = shortObjectName(get("PinSubCategoryObject"));
    std::string cont = unquote(get("ContainerType"));
    if (cont == "Array" || cont == "Set" || cont == "Map") t.container = cont;
    else if (truthy(get("bIsArray"))) t.container = "Array";
    else if (truthy(get("bIsSet"))) t.container = "Set";
    else if (truthy(get("bIsMap"))) t.container = "Map";
    t.isReference = truthy(get("bIsReference"));
    std::string vt = get("PinValueType");
    if (!vt.empty() && vt.front() == '(') {
        auto v = parseStruct(vt);
        t.valueCategory = toLower(unquote(valueOf(v, "TerminalCategory")));
        t.valueSubObject = shortObjectName(valueOf(v, "TerminalSubCategoryObject"));
    }
    return t;
}

std::vector<Link> parseLinks(std::string_view v) {
    std::vector<Link> out;
    for (auto& [k, item] : parseStruct(v)) {
        std::string_view s = trim(k.empty() ? std::string_view(item) : std::string_view{});
        if (s.empty()) continue;
        size_t sp = s.find(' ');
        if (sp == std::string_view::npos) continue;
        out.push_back({std::string(trim(s.substr(0, sp))), std::string(trim(s.substr(sp + 1)))});
    }
    return out;
}

// NSLOCTEXT("ns", "key", "Source") / INVTEXT("x") / LOCTEXT("k", "x") / LOCGEN... / "x" -> the source string
std::string textLiteral(std::string_view v) {
    v = trim(v);
    if (v.empty()) return {};
    if (v.front() == '"') return unquote(v);
    std::string last;
    for (size_t i = 0; i < v.size(); ++i)
        if (v[i] == '"') {
            size_t j = i + 1;
            for (; j < v.size(); ++j) {
                if (v[j] == '\\' && j + 1 < v.size()) ++j;
                else if (v[j] == '"') break;
            }
            last = unquote(v.substr(i, j - i + 1));
            i = j;
        }
    return last;
}

void addPins(Node& n, const RawObject& o, Graph& g, std::set<std::string>& reportedKeys) {
    for (auto& body : o.pins) {
        auto kv = parseStruct(body);
        Pin p;
        p.id = unquote(valueOf(kv, "PinId"));
        p.name = unquote(valueOf(kv, "PinName"));
        p.friendlyName = textLiteral(valueOf(kv, "PinFriendlyName"));
        p.dir = unquote(valueOf(kv, "Direction")) == "EGPD_Output" ? PinDir::Out : PinDir::In;
        p.type = pinTypeFrom(kv, "PinType.");
        for (auto& [k, v] : kv) {
            if (k == "DefaultValue") {
                p.defaultValue = unquote(v);
                p.hasDefault = true;
            } else if (k == "AutogeneratedDefaultValue" && !p.hasDefault) {
                p.defaultValue = unquote(v);
            } else if (k == "DefaultObject") {
                // /Script/Engine.SoundWave'"/Game/Audio/S_Hit.S_Hit"' -> /Game/Audio/S_Hit.S_Hit
                std::string o = trim(v) == "None" ? "" : std::string(trim(unquote(v)));
                size_t q1 = o.find("'\""), q2 = o.rfind("\"'");
                if (q1 != std::string::npos && q2 != std::string::npos && q2 > q1 + 2) o = o.substr(q1 + 2, q2 - q1 - 2);
                p.defaultObject = o;
            } else if (k == "DefaultTextValue") {
                p.defaultText = textLiteral(v);
                p.hasDefault = true;
            } else if (k == "LinkedTo") {
                p.links = parseLinks(v);
            } else if (k == "SubPins") {
                for (auto& l : parseLinks(v)) p.subPins.push_back(l.pinId);
            } else if (k == "ParentPin") {
                std::string_view s = trim(v);
                size_t sp = s.find(' ');
                if (sp != std::string_view::npos) p.parentPin = std::string(trim(s.substr(sp + 1)));
            } else if (k == "bHidden") {
                p.hidden = truthy(v);
            } else if (!knownPinKeys().contains(k) && !k.empty()) {
                if (reportedKeys.insert("pin:" + k).second) g.issues.push_back({o.line, "unrecognised pin property '" + k.substr(0, 60) + "'"});
            }
        }
        if (p.id.empty()) p.id = n.name + "#" + std::to_string(n.pins.size());
        if (p.name.empty()) p.name = p.id;
        n.pins.push_back(std::move(p));
    }
}

void collectVariables(const RawObject& o, Graph& g) {
    for (auto& [k, v] : o.props) {
        if (stripIndex(k) != "NewVariables") continue;
        auto kv = parseStruct(v);
        Variable var;
        var.name = unquote(valueOf(kv, "VarName"));
        if (var.name.empty()) continue;
        std::string vt = valueOf(kv, "VarType");
        if (!vt.empty() && vt.front() == '(') var.type = pinTypeFrom(parseStruct(vt), "");
        var.defaultValue = unquote(valueOf(kv, "DefaultValue"));
        std::string md = valueOf(kv, "MetaDataArray");
        if (!md.empty() && md.front() == '(')
            for (auto& [mk, mv] : parseStruct(md)) {
                auto e = parseStruct(mk.empty() ? mv : std::string());
                if (toLower(unquote(valueOf(e, "DataKey"))) == "tooltip") var.tooltip = unquote(valueOf(e, "DataValue"));
            }
        var.declared = true;
        g.variables.push_back(std::move(var));
    }
}

void collect(const RawObject& o, const std::string& graphName, Graph& g, const Limits& limits, std::set<std::string>& reportedKeys) {
    std::string cls = o.cls;
    std::string shortCls = cls;
    if (size_t d = cls.find_last_of('.'); d != std::string::npos) shortCls = cls.substr(d + 1);
    bool isNode = startsWith(shortCls, "K2Node_") || startsWith(shortCls, "EdGraphNode_") || startsWith(shortCls, "MaterialGraphNode");
    if (isNode) {
        if (g.nodes.size() >= limits.maxNodes) {
            if (!g.truncated) g.issues.push_back({o.line, "node limit reached; remaining nodes ignored"});
            g.truncated = true;
            return;
        }
        Node n;
        n.cls = shortCls;
        n.classPath = cls;
        n.name = o.name.empty() ? shortCls + "_anon" + std::to_string(g.nodes.size()) : o.name;
        n.graph = graphName;
        n.line = o.line;
        for (auto& [k, v] : o.props) {
            std::string key = stripIndex(k);
            if (key == "PinNames" || key == "EnumEntries" || key == "ShowPinForProperties") {
                std::string& acc = n.props[key];
                acc += (acc.empty() ? "" : "\n") + unquote(v);
            } else {
                n.props[k] = v;
            }
            if (!knownNodeKeys().contains(key) && reportedKeys.insert(shortCls + ":" + key).second)
                g.issues.push_back({o.line, "unrecognised property '" + key.substr(0, 60) + "' on " + shortCls.substr(0, 60)});
        }
        for (const char* refKey : {"FunctionReference", "EventReference", "VariableReference", "DelegateReference", "MemberReference"}) {
            auto it = n.props.find(refKey);
            if (it == n.props.end()) continue;
            auto kv = parseStruct(it->second);
            n.memberName = unquote(valueOf(kv, "MemberName"));
            n.memberParent = shortObjectName(valueOf(kv, "MemberParent"));
            n.selfContext = truthy(valueOf(kv, "bSelfContext")) || n.memberParent.empty();
            break;
        }
        auto prop = [&](const char* k) {
            auto it = n.props.find(k);
            return it == n.props.end() ? std::string() : it->second;
        };
        if (shortCls == "K2Node_CustomEvent") n.memberName = unquote(prop("CustomFunctionName"));
        else if (shortCls == "K2Node_MacroInstance") {
            auto kv = parseStruct(prop("MacroGraphReference"));
            n.memberName = shortObjectName(valueOf(kv, "MacroGraph"));
            n.memberParent = shortObjectName(valueOf(kv, "GraphBlueprint"));
        } else if (shortCls == "K2Node_InputAction") n.memberName = unquote(prop("InputActionName"));
        else if (shortCls == "K2Node_InputAxisEvent") n.memberName = unquote(prop("InputAxisName"));
        else if (shortCls == "K2Node_InputKey") {
            std::string k = prop("InputKey");
            n.memberName = k.empty() ? "" : (k.front() == '(' ? unquote(valueOf(parseStruct(k), "KeyName")) : unquote(k));
        } else if (shortCls == "K2Node_EnhancedInputAction") n.memberName = shortObjectName(prop("InputAction"));
        else if (shortCls == "K2Node_DynamicCast") n.memberName = shortObjectName(prop("TargetType"));
        else if (shortCls == "K2Node_MakeStruct" || shortCls == "K2Node_BreakStruct") n.memberName = shortObjectName(prop("StructType"));
        else if (shortCls == "K2Node_Timeline") n.memberName = unquote(prop("TimelineName"));
        else if (shortCls == "K2Node_ComponentBoundEvent" || shortCls == "K2Node_ActorBoundEvent") {
            n.memberName = unquote(prop("DelegatePropertyName"));
            n.memberParent = unquote(prop("ComponentPropertyName"));
        } else if (shortCls == "K2Node_CreateDelegate") n.memberName = unquote(prop("SelectedFunctionName"));
        else if (shortCls == "K2Node_SwitchEnum") n.memberParent = shortObjectName(prop("Enum"));
        if (auto it = n.props.find("NodeComment"); it != n.props.end()) n.comment = unquote(it->second);
        addPins(n, o, g, reportedKeys);
        g.nodes.push_back(std::move(n));
        return;
    }
    // containers / other objects
    std::string childGraph = graphName;
    if (shortCls == "EdGraph") {
        childGraph = o.name;
        g.graphNames.push_back(o.name);
    } else if (shortCls == "Blueprint" || shortCls == "AnimBlueprint" || shortCls == "WidgetBlueprint") {
        if (g.blueprintName.empty()) g.blueprintName = o.name;
        collectVariables(o, g);
    } else if (!o.children.empty()) {
        // container (e.g. a level actor wrapping components) - descend
    } else {
        g.ignoredObjects.push_back((shortCls.empty() ? "(no class)" : shortCls.substr(0, 80)) + " " + o.name.substr(0, 80));
    }
    for (auto& c : o.children) collect(c, childGraph, g, limits, reportedKeys);
}
} // namespace

Graph buildGraph(const RawParse& raw, const Limits& limits) {
    Graph g;
    g.issues = raw.issues;
    g.truncated = raw.truncated;
    std::set<std::string> reportedKeys;
    for (auto& o : raw.objects) collect(o, "", g, limits, reportedKeys);
    // Links: keep the ones whose target exists, and make every link bidirectional (a hand-edited paste may list only one side).
    std::map<std::string, size_t> byName;
    // node names are unique per graph (a whole-Blueprint export repeats K2Node_CallFunction_0 in every graph): links are graph-local
    for (size_t i = 0; i < g.nodes.size(); ++i) byName.emplace(g.nodes[i].graph + "\x1f" + g.nodes[i].name, i);
    std::set<std::string> reportedLinks;
    struct Add {
        size_t node;
        std::string pin;
        Link link;
    };
    std::vector<Add> adds;
    for (size_t i = 0; i < g.nodes.size(); ++i) {
        Node& n = g.nodes[i];
        for (auto& p : n.pins) {
            std::vector<Link> kept;
            for (auto& l : p.links) {
                auto it = byName.find(n.graph + "\x1f" + l.node);
                const Pin* tp = it == byName.end() ? nullptr : g.nodes[it->second].pinById(l.pinId);
                if (!tp) {
                    if (reportedLinks.insert(n.name + "/" + p.name).second)
                        g.issues.push_back({n.line, "link from " + n.name.substr(0, 60) + "." + p.name.substr(0, 40) + " to a node or pin that is not in the input (dropped)"});
                    continue;
                }
                bool back = false;
                for (auto& bl : tp->links)
                    if (bl.node == n.name && bl.pinId == p.id) back = true;
                if (!back) adds.push_back({it->second, tp->id, {n.name, p.id}});
                kept.push_back(l);
            }
            p.links = std::move(kept);
        }
    }
    for (auto& a : adds)
        for (auto& p : g.nodes[a.node].pins)
            if (p.id == a.pin) {
                bool dup = false;
                for (auto& l : p.links) dup = dup || (l.node == a.link.node && l.pinId == a.link.pinId);
                if (!dup) p.links.push_back(a.link);
            }
    return g;  // unknown node classes are reported by the converter, with the node
}

Graph parseGraph(std::string_view text, const Limits& limits) { return buildGraph(parseT3D(text, limits), limits); }

bool isKnownNodeClass(std::string_view cls) { return knownClasses().contains(std::string(cls)); }

