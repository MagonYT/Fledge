std::string unquote(std::string_view v) {
    v = trim(v);
    if (v.size() < 2 || v.front() != '"') return std::string(v);
    std::string out;
    out.reserve(v.size());
    for (size_t i = 1; i < v.size(); ++i) {
        char c = v[i];
        if (c == '"') break;
        if (c == '\\' && i + 1 < v.size()) {
            char n = v[++i];
            switch (n) {
                case 'n': out += '\n'; break;
                case 'r': out += '\r'; break;
                case 't': out += '\t'; break;
                default: out += n; break;  // \" \\ \'
            }
            continue;
        }
        out += c;
    }
    return out;
}

std::vector<std::pair<std::string, std::string>> parseStruct(std::string_view value, int maxDepth) {
    std::vector<std::pair<std::string, std::string>> out;
    value = trim(value);
    if (value.empty() || value.front() != '(') return out;
    size_t i = 1;
    size_t guard = 0;
    while (i < value.size() && guard++ < value.size() + 4) {
        while (i < value.size() && (value[i] == ' ' || value[i] == '\t')) ++i;
        if (i >= value.size() || value[i] == ')') break;
        size_t end = scanValue(value, i, maxDepth);
        std::string_view item = value.substr(i, end - i);
        if (!trim(item).empty()) out.push_back(splitKeyValue(item));
        if (end >= value.size() || value[end] == ')') break;
        i = end + 1;  // skip ','
    }
    return out;
}

RawParse parseT3D(std::string_view text, const Limits& limits) {
    RawParse r;
    if (text.size() > limits.maxInputBytes) {
        r.issues.push_back({0, "input larger than the limit"});
        r.truncated = true;
        return r;
    }
    if (text.size() >= 3 && static_cast<unsigned char>(text[0]) == 0xEF && static_cast<unsigned char>(text[1]) == 0xBB &&
        static_cast<unsigned char>(text[2]) == 0xBF)
        text.remove_prefix(3);
    std::vector<RawObject> stack;
    int skipDepth = 0;  // objects nested beyond maxObjectNesting are skipped
    size_t objects = 0;
    int line = 0;
    size_t pos = 0;
    while (pos <= text.size()) {
        size_t nl = text.find('\n', pos);
        if (nl == std::string_view::npos) nl = text.size();
        std::string_view raw = text.substr(pos, nl - pos);
        pos = nl + 1;
        ++line;
        std::string_view l = trim(raw);
        if (l.empty()) {
            if (nl >= text.size()) break;
            continue;
        }
        if (startsWithCI(l, "Begin Object")) {
            if (skipDepth > 0 || static_cast<int>(stack.size()) >= limits.maxObjectNesting) {
                if (skipDepth == 0) r.issues.push_back({line, "objects nested too deeply; inner objects skipped"});
                ++skipDepth;
            } else if (++objects > limits.maxNodes + 1024) {
                r.issues.push_back({line, "too many objects; the rest of the input was not parsed"});
                r.truncated = true;
                break;
            } else {
                RawObject o;
                o.line = line;
                std::string_view rest = trim(l.substr(12));
                // attributes: Class=... Name="..." ExportPath=... (space separated; values may be quoted)
                size_t i = 0;
                while (i < rest.size()) {
                    while (i < rest.size() && rest[i] == ' ') ++i;
                    size_t eq = rest.find('=', i);
                    if (eq == std::string_view::npos) break;
                    std::string key(trim(rest.substr(i, eq - i)));
                    size_t j = eq + 1;
                    bool dq = false, sq = false;
                    size_t start = j;
                    for (; j < rest.size(); ++j) {
                        char c = rest[j];
                        if (dq) {
                            if (c == '\\' && j + 1 < rest.size()) ++j;
                            else if (c == '"') dq = false;
                        } else if (sq) {
                            if (c == '\'') sq = false;
                        } else if (c == '"') dq = true;
                        else if (c == '\'') sq = true;
                        else if (c == ' ') break;
                    }
                    std::string val(rest.substr(start, j - start));
                    if (key == "Class") o.cls = val;
                    else if (key == "Name") o.name = unquote(val);
                    i = j;
                }
                stack.push_back(std::move(o));
            }
        } else if (startsWithCI(l, "End Object")) {
            if (skipDepth > 0) {
                --skipDepth;
            } else if (stack.empty()) {
                r.issues.push_back({line, "'End Object' without 'Begin Object'"});
            } else {
                RawObject o = std::move(stack.back());
                stack.pop_back();
                if (stack.empty()) r.objects.push_back(std::move(o));
                else stack.back().children.push_back(std::move(o));
            }
        } else if (skipDepth > 0) {
            // inside a skipped object
        } else if (stack.empty()) {
            if (!startsWithCI(l, "Begin Map") && !startsWithCI(l, "End Map") && !startsWithCI(l, "Begin Level") && !startsWithCI(l, "End Level"))
                r.issues.push_back({line, "text outside 'Begin Object ... End Object' ignored"});
        } else if (startsWithCI(l, "CustomProperties")) {
            std::string_view rest = trim(l.substr(16));
            size_t sp = rest.find_first_of(" (");
            std::string kind(trim(rest.substr(0, sp)));
            std::string_view body = sp == std::string_view::npos ? std::string_view{} : trim(rest.substr(sp));
            if (kind == "Pin" || kind == "UserDefinedPin") {
                if (body.empty() || body.front() != '(') {
                    r.issues.push_back({line, "malformed CustomProperties " + kind + " (no '(')"});
                } else if (kind == "Pin") {
                    if (stack.back().pins.size() >= limits.maxPinsPerNode) r.issues.push_back({line, "too many pins on one node; extra pins ignored"});
                    else stack.back().pins.emplace_back(body);
                } else {
                    stack.back().userPins.emplace_back(body);
                }
            } else {
                r.issues.push_back({line, "unrecognised 'CustomProperties " + kind.substr(0, 40) + "' ignored"});
            }
        } else {
            auto kv = splitKeyValue(l);
            if (kv.first.empty()) r.issues.push_back({line, "line without '=' ignored"});
            else stack.back().props.push_back(std::move(kv));
        }
        if (nl >= text.size()) break;
    }
    if (!stack.empty() || skipDepth > 0) {
        r.issues.push_back({line, "input ended inside 'Begin Object' (truncated paste?); the open objects were closed"});
        r.truncated = true;
        while (!stack.empty()) {
            RawObject o = std::move(stack.back());
            stack.pop_back();
            if (stack.empty()) r.objects.push_back(std::move(o));
            else stack.back().children.push_back(std::move(o));
        }
    }
    return r;
}

